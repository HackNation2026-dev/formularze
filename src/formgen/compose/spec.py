"""Flat intermediate specification: what the extraction stage (LLM + heuristics) produces.

Only the *subject of the application* (pages 2..n) and a handful of global
decisions live here. Everything template-driven (page 1, contact page, finish
page, addresses, JSONata, grid, UUIDs, flow) is generated by ``assemble.compose``.
"""

from __future__ import annotations

from pydantic import BaseModel
from pydantic import Field as PField

from formgen.schema.model import FieldType, Validator


class ApplicantKinds(BaseModel):
    """Who may file this form. Drives the 'Podmiot wniosku' radio and the conditional sections."""

    self_person: bool = True  # "Swoim"
    other_person: bool = False  # "Innej osoby" (pełnomocnik osoby fizycznej)
    legal_entity: bool = False  # "Osoby prawnej lub jednostki organizacyjnej"

    @property
    def needs_subject_section(self) -> bool:
        return self.other_person or self.legal_entity


class Condition(BaseModel):
    """Show the element only when ``field`` (tech_name on the same page) equals ``value``."""

    field: str
    value: str
    negate: bool = False


class FieldSpec(BaseModel):
    label: str
    kind: FieldType = FieldType.TEXT_FIELD
    tech_name: str | None = None
    description: str = ""
    options: list[str] = PField(default_factory=list)
    required: bool = True
    validators: list[Validator] = PField(default_factory=list)
    dictionary: str | None = None
    default: str | None = None
    initial_data: str | None = None  # e.g. "MLPZ.email" -> readOnly EXTERNAL_SYSTEM
    read_only: bool = False
    visible_when: list[Condition] = PField(default_factory=list)
    tooltip: str = ""
    # for CONSENT_SECTION: list of (text, required)
    consents: list[tuple[str, bool]] = PField(default_factory=list)


class SectionSpec(BaseModel):
    title: str
    tech_name: str | None = None
    description: str = ""
    fields: list[FieldSpec] = PField(default_factory=list)
    repeating: bool = False
    visible_when: list[Condition] = PField(default_factory=list)


class PageSpec(BaseModel):
    title: str
    sections: list[SectionSpec] = PField(default_factory=list)


class FormSpec(BaseModel):
    title: str
    office_name: str = ""
    office_is_organ: bool = False  # "Organ, do którego..." vs "Urząd, do którego..."
    applicant: ApplicantKinds = PField(default_factory=ApplicantKinds)
    identity_source: str = "MLPZ"  # or "PESEL"
    include_pesel: bool = True
    pages: list[PageSpec] = PField(default_factory=list)
    extra_consents: list[tuple[str, bool]] = PField(default_factory=list)
    summary_text: str = ""
    with_validators: bool = True
    # optional override of the contact page title ("Kontakt i zgody" / "Kontakt z urzędem")
    contact_page_title: str = "Kontakt i zgody"
